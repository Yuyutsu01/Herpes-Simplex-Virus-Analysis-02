"""
Script to generate README.md files for data/, figures/, tables/, scripts/, and tests/.
"""
from pathlib import Path

def generate_subfolder_readmes():
    base_dir = Path(".")

    # 1. data/README.md
    data_readme = """# Data Directory Guide

This directory houses the sequence data, physicochemical features, protein language model embeddings, benchmark datasets, and split manifests for the HSV-1 and HSV-2 temporal proteomics study.

---

## Directory Organization

```text
data/
├── raw/                      # Immutable primary source FASTA files and SHA-256 manifest
│   ├── hsv1.fasta           # Reference proteome for HSV-1 (strain 17)
│   ├── hsv2.fasta           # Reference proteome for HSV-2 (strain HG52)
│   └── RAW_DATA_CHECKSUMS.sha256 # Cryptographic hashes for raw FASTAs
├── processed/                # Curated sequences, embeddings, features, and benchmarks
└── cache/                    # Local processing caches (if retained)
```

## Key Files in `data/processed/`

- `all_curated_proteins.csv`: Consolidated inventory of quality-filtered protein sequences.
- `physicochemical_properties.csv`: 29 sequence-derived biophysical indices (pI, GRAVY, instability, charge, MW, AA frequencies).
- `esm2_t33_650M_embeddings.npz` / `.csv`: Mean-pooled 1280-dim ESM-2 650M sequence embeddings.
- `esm2_embeddings_manifest.json`: Array index to UniProt accession mapping.
- `temporal_evidence_adjudication.json`: Adjudicated kinetic classifications with PubMed citations and experimental quotes.
- `benchmark_dataset_687.csv`: Authoritative 687-sequence, 63-family direct-evidence benchmark.
- `family_disjoint_5fold_splits.csv`: 5-fold cross-validation partition assignments grouped by homology group.

For full schemas and column definitions, see [docs/DATA_DICTIONARY.md](file:///docs/DATA_DICTIONARY.md).
"""
    with open(base_dir / "data" / "README.md", "w", encoding="utf-8") as f:
        f.write(data_readme.strip() + "\n")

    # 2. figures/README.md
    figures_readme = """# Publication Figures Directory

This directory contains the publication-ready figures for the HSV-1 and HSV-2 research paper. Each visual is provided in both vector PDF and 300 DPI PNG formats, alongside the exact data CSV used to render it.

---

## Figure Inventory

| Figure ID | Title | Formats | Underlying Data |
|---|---|---|---|
| Figure 1 | Study Workflow & Validation Architecture | `.pdf`, `.png` | `figure_1_study_workflow_data.csv` |
| Figure 2 | Universal Dataset Composition & Cohorts | `.pdf`, `.png` | `figure_2_dataset_composition_data.csv` |
| Figure 3 | Temporal Evidence Distribution & Benchmark | `.pdf`, `.png` | `figure_3_temporal_label_evidence_data.csv` |
| Figure 4 | ESM-2 Latent Embedding Geometry & PCA | `.pdf`, `.png` | `figure_4_embedding_geometry_data.csv` |
| Figure 5 | Comparative Model Performance (ROC / PR / F1) | `.pdf`, `.png` | `figure_5_model_comparison_data.csv` |
| Figure 6 | Family-Level Prediction Profiles & Confusion | `.pdf`, `.png` | `figure_6_family_predictions_data.csv` |
| Figure 7 | Multi-Endpoint & Dimensional Sensitivity | `.pdf`, `.png` | `figure_7_sensitivity_analysis_data.csv` |
| Figure 8 | Unsupervised Manifold Projections (UMAP / t-SNE) | `.pdf`, `.png` | `figure_8_unsupervised_structure_data.csv` |

All figures are programmatically generated by [scripts/16_generate_publication_visuals.py](file:///scripts/16_generate_publication_visuals.py).
"""
    with open(base_dir / "figures" / "README.md", "w", encoding="utf-8") as f:
        f.write(figures_readme.strip() + "\n")

    # 3. tables/README.md
    tables_readme = """# Publication Tables Directory

This directory contains the primary and supplementary tables for the manuscript, provided in both CSV (for programmatic consumption) and GitHub-flavored Markdown (for inspection).

---

## Main Manuscript Tables

- `table_1_dataset_accounting.csv` / `.md`: Universal corpus accounting across 22,710 records.
- `table_2_model_configurations.csv` / `.md`: Mathematical formulations, hyperparameters, and regularization settings.
- `table_3_main_performance.csv` / `.md`: Comprehensive comparative performance with 95% bootstrap CIs across 63 families.
- `table_4_statistical_comparisons.csv` / `.md`: Paired McNemar hypothesis tests, odds ratios, and Holm-adjusted p-values.
- `table_5_temporal_evidence_summary.csv` / `.md`: Temporal evidence levels, experimental assays, and literature concordance.
- `table_6_sensitivity_analysis.csv` / `.md`: Endpoint sensitivity, fragment perturbation, and label flip tests.
- `table_7_unsupervised_summary.csv` / `.md`: Effective rank calculations, scree analysis, and variance explained.

## Supplementary Tables

- `table_s1_supervised_benchmark_687.csv`: Complete 687-sequence benchmark ledger.
- `table_s2_split_manifest_5fold.csv`: 5-fold cross-validation partition assignments.
- `table_s3_family_oof_predictions.csv`: Out-of-fold predicted probabilities for 63 gene families.
- `table_s4_sequence_oof_predictions.csv`: Sequence-level out-of-fold predictions.
- `table_s5_temporal_evidence_ledger_63.csv`: PubMed citations, quotes, and experimental assays.
- `table_s6_corpus_lineage_accounting.csv`: Universal 22,710-record provenance ledger.
- `table_s7_clustering_robustness.csv`: Silhouette and Davies-Bouldin metrics across clustering algorithms.
- `table_s8_reference_claim_support.csv`: Traceability ledger linking manuscript claims to empirical code outputs.
"""
    with open(base_dir / "tables" / "README.md", "w", encoding="utf-8") as f:
        f.write(tables_readme.strip() + "\n")

    # 4. scripts/README.md
    scripts_readme = """# Scripts Directory Guide

This directory houses the executable Python scripts supporting the entire scientific pipeline. Scripts follow a consistent phase-based naming convention and preserve end-to-end execution order.

---

## Canonical Pipeline Execution Order

| Phase | Canonical Script | Primary Function | Key Output |
|---|---|---|---|
| **01** | `01_curate_proteomes.py` | Ingest raw FASTA sequences and filter non-canonical residues | `data/processed/all_curated_proteins.csv` |
| **02** | `02_extract_physicochemical_properties.py` | Extract 29 biophysical indices (pI, GRAVY, charge, etc.) | `data/processed/physicochemical_properties.csv` |
| **02** | `03_extract_esm2_embeddings.py` | Extract 1280-dim embeddings from ESM-2 650M | `data/processed/esm2_t33_650M_embeddings.npz` |
| **03** | `04_build_temporal_benchmark.py` | Adjudicate literature evidence and build 5-fold CV splits | `data/processed/benchmark_dataset_687.csv` |
| **05** | `05_train_models.py` | Train baseline majority, PhysChem LR/RF, ESM-2 LR/RF | `results/predictions/oof_predictions_*.csv` |
| **06** | `06_evaluate_models.py` | Compute family Macro-F1, bootstrap CIs, exact McNemar | `tables/table_3_main_performance.csv` |
| **07** | `07_interpretability_analysis.py` | PCA decomposition and correlation with biophysical features | `tables/table_7_pca_interpretation.csv` |
| **08** | `08_run_independent_validation.py` | Zero-hardcoding verification and pipeline reconciliation | `reports/validation/` |
| **09** | `09_run_adversarial_challenge.py` | Evaluate sensitivity to effective rank and test choices | `tables/table_8_adversarial_reconciliation.csv` |
| **10** | `16_generate_publication_visuals.py` | Generate publication figures (PDF/PNG) and tables | `figures/` and `tables/` |

## Auxiliary Utility Scripts
- `verify_raw_checksums.py`: Verifies cryptographic SHA-256 hashes of immutable raw FASTA data.
- `setup_manuscript.py`: Bundles submission files into `manuscript/`.

All scripts use deterministic random seeds (`seed=42`) and relative path resolution from the project root.
"""
    with open(base_dir / "scripts" / "README.md", "w", encoding="utf-8") as f:
        f.write(scripts_readme.strip() + "\n")

    # 5. tests/README.md
    tests_readme = """# Automated Test Suite

This directory contains the automated test suite for the `Herpes-Simplex-Virus-Analysis-02` project. The test suite enforces scientific invariants, data integrity, statistical validity, zero hardcoding, and repository structure.

---

## Test Organization

- `test_01_raw_fasta_integrity.py`: Validates raw FASTA checksums, accession formats, and record counts.
- `test_02_sequence_curation_qc.py`: Asserts quality filtering, non-canonical residue handling, and length thresholds.
- `test_03_physicochemical_properties.py`: Asserts non-null values and valid biophysical domains for all 29 indices.
- `test_04_esm2_embeddings.py`: Asserts embedding matrix dimensions, finite values, and manifest alignment.
- `test_05_unsupervised_analysis.py`: Validates PCA coordinates, scree calculations, and manifold invariants.
- `test_06_temporal_evidence_audit.py`: Asserts PubMed citations, evidence grading, and kinetic classification logic.
- `test_07_benchmark_dataset_integrity.py`: Asserts 687 rows, 63 homology groups, and class balance.
- `test_08_family_disjoint_splits.py`: Asserts zero homology group overlap across the 5 cross-validation folds.
- `test_09_model_training_reproducibility.py`: Validates deterministic model convergence and seed stability.
- `test_10_statistical_inference_audit.py`: Recomputes McNemar tables, discordant pairs, and Holm-Bonferroni math.
- `test_11_robustness_analysis.py`: Asserts model sensitivity under feature ablation and label flips.
- `test_12_representation_interpretation.py`: Validates PCA effective rank math and biophysical correlation matrices.
- `test_13_independent_validation.py`: Asserts zero hardcoding in pipeline results and ledgers.
- `test_14_evidence_audit_consistency.py`: Asserts metric alignment between manuscript tables and prediction files.
- `test_15_independent_reviewer_audit.py`: Validates adversarial challenges, error reporting, and claim qualification.
- `test_16_publication_visuals.py`: Asserts existence, non-zero size, and integrity of all publication figures and tables.
- `test_repository_structure.py`: Validates repository file layout, internal markdown links, and raw data immutability.

## Running Tests

Execute the full suite using pytest:

```bash
pytest tests/ -v
```
"""
    with open(base_dir / "tests" / "README.md", "w", encoding="utf-8") as f:
        f.write(tests_readme.strip() + "\n")

    print("Generated READMEs in data/, figures/, tables/, scripts/, and tests/.")

if __name__ == "__main__":
    generate_subfolder_readmes()
