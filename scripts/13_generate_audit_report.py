def load_and_verify_inputs() -> Dict[str, Any]:
    """Loads all Step 13 CSVs and manifest, verifying existence and non-emptiness."""
    tables = {}
    for path, name in [
        (FILE_HARDCODING_CSV, "hardcoding"),
        (FILE_INTEGRITY_CSV, "integrity"),
        (FILE_ADJUDICATION_CSV, "adjudication"),
        (FILE_SPLIT_CSV, "splits"),
        (FILE_RETRAINED_OOF, "oof"),
        (FILE_SEQ_METRICS, "seq_metrics"),
        (FILE_FAM_METRICS, "fam_metrics"),
        (FILE_STAT_INFERENCE, "stat_inference"),
    ]:
        if not os.path.exists(path) or os.stat(path).st_size == 0:
            raise FileNotFoundError(f"Missing or empty required table: {path}")
        tables[name] = pd.read_csv(path)

    with open(FILE_MANIFEST, "r", encoding="utf-8") as f:
        tables["manifest"] = json.load(f)

    return tables


